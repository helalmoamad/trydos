/// رمزٌ متحرّك يعمل مرّةً ثم يستقرّ.
///
/// وما لا حركة له — أو ما تعذّر تحميله — يُرسم رمزَ الهاتف بنفس المقاس، فلا
/// تظهر خلّةٌ في الشبكة.
class AnimatedEmoji extends StatelessWidget {
  const AnimatedEmoji({super.key, required this.emoji, required this.size});

  final String emoji;
  final double size;

  @override
  Widget build(BuildContext context) {
    final String? asset = AnimatedEmojiV2.assetOf(emoji);
    if (asset == null) return _plain();

    return SizedBox(
      width: size.w,
      height: size.w,
      child: Lottie.asset(
        asset,
        repeat: false,
        fit: BoxFit.contain,
        // الرمز الساكن **حتى تجهز الحركة**، كما يفعل الملف صراحةً:
        // «حتى تُحمَّل الحركة — أو إن تعذّرت — يُرسم رمز الهاتف مكانها، فلا
        // يظهر في الشريط مربّعٌ فارغ». وقراءةُ الملف من الأصول تأخذ إطارات،
        // فبلا هذا تُفتح القائمة بخاناتٍ خاوية.
        frameBuilder: (context, child, composition) =>
            composition == null ? _plain() : child,
        // ملفٌّ ناقص أو تالف: الرمز الساكن مكانه بلا صندوقٍ أحمر.
        errorBuilder: (_, _, _) => _plain(),
      ),
    );
  }

  /// رمز الهاتف الساكن. مقاسه 0.9 من المقاس المطلوب كما في الويب (27 لـ30).
  Widget _plain() => SizedBox(
    width: size.w,
    height: size.w,
    child: Center(
      child: Text(
        emoji,
        style: TextStyle(fontSize: (size * 0.9).sp, height: 1),
      ),
    ),
  );
}
